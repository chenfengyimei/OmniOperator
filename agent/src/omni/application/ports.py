"""Application boundaries. Implementations belong to adapters."""

from __future__ import annotations

from collections.abc import Callable, Mapping, Sequence
from contextlib import AbstractContextManager
from typing import Protocol, TypeVar

from ..domain.contracts import JSON, ActionResult, InvocationContext, ModelReply, ToolSpec
from ..domain.settings import Settings

T = TypeVar("T")
Record = dict[str, JSON]


class Clock(Protocol):
    def now(self) -> str: ...
    def monotonic(self) -> float: ...


class Ids(Protocol):
    def new(self) -> str: ...


class ModelPort(Protocol):
    async def complete(
        self, messages: Sequence[Record], tools: Sequence[ToolSpec], settings: Settings
    ) -> ModelReply: ...


class CapabilityPort(Protocol):
    async def invoke(
        self, name: str, arguments: Mapping[str, JSON], *, operation_id: str, context: InvocationContext
    ) -> ActionResult: ...
    async def close(self, timeout_s: float) -> bool: ...


class SecretStore(Protocol):
    def get(self, reference: str) -> str | None: ...
    def set(self, reference: str, value: str) -> None: ...
    def delete(self, reference: str) -> None: ...


class UnitOfWork(Protocol):
    def initialize(self) -> Record: ...
    def create_agent(self, name: str) -> Record: ...
    def issue_token(self, token_hash: str, expires_at: str) -> None: ...
    def token_valid(self, token_hash: str) -> bool: ...
    def probe_write(self) -> None: ...
    def accept_turn(self, agent_id: str, session_id: str | None, key: str, text: str, config: Record) -> Record: ...
    def get_run(self, agent_id: str, run_id: str) -> Record: ...
    def transition(self, agent_id: str, run_id: str, state: str, error_code: str = "") -> None: ...
    def event(self, agent_id: str, run_id: str, kind: str, data: Record) -> int: ...
    def messages(self, agent_id: str, session_id: str, limit: int = 50) -> list[Record]: ...
    def context_messages(self, agent_id: str, run_id: str) -> list[Record]: ...
    def snapshot(self, agent_id: str, run_id: str, message_ids: list[str], memory_ids: list[str]) -> str: ...
    def finish(self, agent_id: str, run_id: str, text: str, delivery: Record | None = None) -> None: ...
    def settings(self, agent_id: str) -> Record: ...
    def settings_put(self, agent_id: str, value: Record, revision: int) -> Record: ...
    def reserve_call(self, agent_id: str, run_id: str, amount: int, limit: int, model: str) -> str: ...
    def settle_call(
        self, agent_id: str, call_id: str, reply: ModelReply | None, *, known_not_sent: bool = False
    ) -> None: ...
    def prepare_action(self, agent_id: str, run_id: str, spec: ToolSpec, arguments: Record, policy: int) -> Record: ...
    def authorize_action(self, agent_id: str, action_id: str) -> Record: ...
    def settle_action(self, agent_id: str, action_id: str, result: ActionResult) -> None: ...
    def pending_approvals(self, agent_id: str) -> list[Record]: ...
    def resolve_approval(self, agent_id: str, approval_id: str, allowed: bool, policy: int) -> None: ...
    def recover(self) -> Record: ...
    def cancel(self, agent_id: str, run_id: str) -> None: ...
    def action(self, agent_id: str, action_id: str) -> Record: ...
    def remember(
        self, agent_id: str, content: str, *, kind: str = "fact", message_id: str | None = None, quote: str = ""
    ) -> Record: ...
    def forget(self, agent_id: str, memory_id: str) -> None: ...
    def search_memory(self, agent_id: str, query: str, limit: int = 20) -> list[Record]: ...
    def cancel_approvals(self) -> None: ...
    def close_run_actions(self, agent_id: str, run_id: str) -> None: ...
    def query(self, kind: str, agent_id: str, *, after: int = 0, limit: int = 100, **filters: str) -> list[Record]: ...


class DatabasePort(Protocol):
    async def write(self, operation: Callable[[UnitOfWork], T]) -> T: ...
    async def read(self, operation: Callable[[UnitOfWork], T]) -> T: ...
    async def close(self) -> None: ...


class Observer(Protocol):
    def context(self, **fields: str) -> AbstractContextManager[None]: ...
    def span(self, name: str) -> AbstractContextManager[object]: ...
