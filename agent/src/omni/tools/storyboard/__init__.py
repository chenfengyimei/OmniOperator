"""视频理解能力域：把一段视频变成模型能"引用"的画面索引。

为什么需要（对照 xuexi/NOTES.md §6）：

参考项目 dsh-video-storyboard 证明了「纯文本模型装一双能翻页的眼睛」是有用的：
输入视频 → 输出一张宫格图，每格烧编号、对应一段时间、下面挂着那段时间说过的台词，
底部一条与画面同时间轴的音频包络。模型因此能「看」、能「引用第 5 格」、能「再放大看这 3 秒」。

**我们不抄它的取流层**：它依赖 ffmpeg + yt-dlp + cookies.txt，
而我们已有 B站 WBI 直链（tools/bilibili/api.py）与已装的 PyAV（随 faster-whisper 进来），
所以本域**零新增外部依赖**——不装 ffmpeg 也能跑。

**我们抄的是三件事**（算法与设计，代码独立实现）：

1. **切点用 HSV 三通道差，不用亮度差**——同亮度换色的剪辑，亮度差看不见；
2. **一镜一格 + 可寻址索引**——格号能反查绝对时间，模型引用一次就闭环；
3. **如实报最小格的尺寸**，不报平均——模型该知道自己看不清什么。

明确不做：不做变尺寸格子（1/1…1/8 档位），我们用固定宫格——
一张图固定占 token，把格子缩小只丢信息不省 token，这笔账参考项目自己也算过。
不做音频包络画在图上（我们已有 ASR 文本，单独出包络图只是多花一份视觉 token）。

分层：本模块是**纯逻辑**（零 I/O、零网络），只吃已解码的帧序列；
取流与工具包装在 tools.py 与 tools/video/ 下。
"""
from __future__ import annotations

# 切点检测的扫描分辨率：64×36 足够抓住画面突变，再高只是白烧 CPU。
SCAN_WIDTH = 64
SCAN_HEIGHT = 36

# 清晰度评分用的最小边长（Laplacian 方差在这尺度上才有区分度）。
SHARPNESS_EDGE = 96

# 帧率再高，逐帧全量扫描也不划算；抽样到约这个帧率足够抓切点。
MAX_SCAN_FPS = 12.0

# 扫描的帧预算：一段片子最多看这么多帧（12fps 下约 42 分钟）。
# **超出预算不截断，而是抽稀**（见 decode.effective_scan_fps）——
# 真机实测 34 分钟视频需要约 24,600 帧，旧上限 6000 只覆盖前 800 秒（39%），
# 后 20 分钟画面整段丢失。把上限提到 30000 后，34 分钟片子扫描耗时 7s → 18.2s
# （仍是 100× 实时以上），内存恒定（峰值 1.2MB）——代价完全可接受。
MAX_SCAN_FRAMES = 30000

# 抽稀后的最低帧率：再长的片子也至少按这个帧率看过去。
# 2fps 仍然足以抓住剪辑点（镜头切换在时间轴上远宽于 0.5 秒）。
MIN_SCAN_FPS = 2.0
